import { describe, it, expect } from 'vitest';
import { generateTrackingNo, validateTrackingNo } from '@/lib/tracking';

describe('Tracking Quick-Input Validation', () => {
  it('accepts valid tracking numbers generated by generateTrackingNo', () => {
    const validAwb = generateTrackingNo('ABC', 2026);
    const result = validateTrackingNo(validAwb);
    expect(result.isValid).toBe(true);
    expect(result.prefix).toBe('ABC');
  });

  it('rejects empty, short, or non-conforming inputs with friendly errors', () => {
    expect(validateTrackingNo('').isValid).toBe(false);
    expect(validateTrackingNo('ABC').isValid).toBe(false);
    expect(validateTrackingNo('12345678901234').isValid).toBe(false);
    expect(validateTrackingNo('ABC261234').isValid).toBe(false);
  });

  it('detects single-digit check digit tampering', () => {
    const original = generateTrackingNo('ABC', 2026);
    const lastDigit = original.slice(-1);
    const tamperedLast = lastDigit === '0' ? '1' : '0';
    const tampered = original.slice(0, -1) + tamperedLast;

    expect(validateTrackingNo(original).isValid).toBe(true);
    expect(validateTrackingNo(tampered).isValid).toBe(false);
  });

  it('handles lowercase or spaced input after normalization', () => {
    const original = generateTrackingNo('ABC', 2026);
    const lowercase = original.toLowerCase();
    // After trimming / uppercasing in the quick input
    const normalized = lowercase.trim().toUpperCase();
    expect(validateTrackingNo(normalized).isValid).toBe(true);
  });
});
